#Annetaan kolma kokonaista luvut

ensimmaine = int(input("Anna ensimmaine luku: "))
toinen = int(input("Anna toinen luku: "))
kolmas = int(input("Anna kolmas luku: "))

#Tulostetaan keskiarvo tulos
yhtensumma = ensimmaine + toinen + kolmas
keskiarvo = yhtensumma / 3
print("keskiarvo on ", keskiarvo)
